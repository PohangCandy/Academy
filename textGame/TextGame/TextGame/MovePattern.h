#pragma once
//--------------------------------------------------------------------
// 최대 이동 패턴 가짓수
//--------------------------------------------------------------------
#define MAXPATTERNTYPENUM 5

//--------------------------------------------------------------------
// 패턴 반복 횟수
//--------------------------------------------------------------------
#define MAXPATTERNSTEPNUM 24
#include "TextParser.h"

//--------------------------------------------------------------------
//이동 좌표
//--------------------------------------------------------------------
struct tag_Pos
{
	int x = 0;
	int y = 0;
};

//--------------------------------------------------------------------
//적의 이동 패턴
//--------------------------------------------------------------------
struct tag_Pattern
{
	char name[12] = { 0, };
	tag_Pos Steps[MAXPATTERNSTEPNUM] = {0,};
	int stepCount = 0;
	int curStep = 0;
};

extern tag_Pattern PatternType[MAXPATTERNTYPENUM];

//--------------------------------------------------------------------
//패턴 파일에서 데이터 불러오기
//--------------------------------------------------------------------
bool LoadPattern(tag_Pattern pattern[]);


//--------------------------------------------------------------------
//패턴 이름으로 패턴 불러오기
// parameter : 패턴 이름, 저장할 패턴 메모리
//--------------------------------------------------------------------
bool GetPattern(CParser parser, const char* patternName, tag_Pattern* pattern, int patternSize);

